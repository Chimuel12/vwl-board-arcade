#!/usr/bin/env python3
"""
Makes the web copies of the reels for the app and GitHub Pages.

  .venv/bin/python publish_web.py                    # all videos found in ../../videos/kap*/
  .venv/bin/python publish_web.py --src DIR --force  # other source folder / re-encode everything

- media/videos/NNN.mp4   720×1280, H.264 CRF 30, AAC 64k mono (~1.3 MB each; Pages sites must stay < 1 GB)
- media/videos/NNN.jpg   poster 360×640
- js/data/videos.js      manifest: window.VIDEOS = [{n, ch, i, id, term, dur}]  (id = "ch-i", same ids as the Memory pairs)
Unchanged videos are skipped (output newer than the source).
"""
import argparse
import glob
import json
import os
import re
import subprocess
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, "media", "videos")


def load_scripts():
    scripts = []
    for p in sorted(glob.glob(os.path.join(HERE, "scripts", "k*.json"))):
        with open(p, encoding="utf-8") as fh:
            scripts += json.load(fh)
    first = {}
    for s in sorted(scripts, key=lambda s: s["n"]):
        first.setdefault(s["ch"], s["n"])
    return {s["n"]: dict(s, i=s["n"] - first[s["ch"]]) for s in scripts}


def encode(src, n, force):
    mp4, jpg = os.path.join(OUT, f"{n:03d}.mp4"), os.path.join(OUT, f"{n:03d}.jpg")
    if force or not os.path.exists(mp4) or os.path.getmtime(mp4) < os.path.getmtime(src):
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", src, "-vf", "scale=720:1280:flags=lanczos",
                        "-c:v", "libx264", "-preset", "slow", "-crf", "30", "-pix_fmt", "yuv420p",
                        "-c:a", "aac", "-b:a", "64k", "-ac", "1", "-movflags", "+faststart", mp4], check=True)
    cover = src[:-4] + ".jpg"
    if force or not os.path.exists(jpg) or (os.path.exists(cover) and os.path.getmtime(jpg) < os.path.getmtime(cover)):
        # cover image from render.py; otherwise a frame from the video (-ss on a still image yields no frame)
        inp = ["-i", cover] if os.path.exists(cover) else ["-ss", "1.6", "-i", src]
        subprocess.run(["ffmpeg", "-v", "error", "-y", *inp, "-frames:v", "1", "-update", "1",
                        "-vf", "scale=360:640:flags=lanczos", "-q:v", "6", jpg], check=True)
        if not os.path.exists(jpg):
            raise RuntimeError(f"no poster for {n:03d}")
    dur = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", mp4]).decode())
    return n, round(dur, 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=os.path.join(REPO, "..", "videos"))
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--jobs", type=int, default=4)
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    scripts = load_scripts()
    sources = {}
    for f in glob.glob(os.path.join(a.src, "kap*", "*.mp4")):
        m = re.match(r"(\d{3})_", os.path.basename(f))
        if m and int(m.group(1)) in scripts:
            sources[int(m.group(1))] = f
    print(f"{len(sources)} vídeos fuente → {OUT}", flush=True)
    durs = {}
    with ThreadPoolExecutor(a.jobs) as ex:
        for n, d in ex.map(lambda kv: encode(kv[1], kv[0], a.force), sorted(sources.items())):
            durs[n] = d
            if n % 25 == 0:
                print(f"  … {n:03d}", flush=True)
    items = [{"n": n, "ch": scripts[n]["ch"], "i": scripts[n]["i"], "id": f"{scripts[n]['ch']}-{scripts[n]['i']}",
              "term": scripts[n]["term"], "dur": durs[n]} for n in sorted(durs)]
    with open(os.path.join(REPO, "js", "data", "videos.js"), "w", encoding="utf-8") as fh:
        fh.write("/* VWL Essentials · one explainer video per concept (generated by studio/publish_web.py) */\n")
        fh.write("window.VIDEOS = " + json.dumps(items, ensure_ascii=False, separators=(",", ":")) + ";\n")
    size = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
    print(f"✓ {len(items)} vídeos · {size / 1e6:.0f} MB en media/videos · manifest js/data/videos.js")


if __name__ == "__main__":
    main()
